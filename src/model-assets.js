export function modelsForProject(projectId) {
  return MODELS.filter((model) => Number(model.projectId) === Number(projectId)).sort(
    (a, b) => Number(Boolean(b.featured)) - Number(Boolean(a.featured)) || a.id.localeCompare(b.id),
  );
}

export function modelAssetUrl(model) {
  return `/models3d/${encodeURIComponent(model.file)}`;
}

